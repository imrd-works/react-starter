// @ts-check
/**
 * Generates `*.module.scss.d.ts` with the exact class names of each CSS module,
 * so `styles.typo` is a TypeScript error instead of a silent `undefined`.
 *
 *   node scripts/css-module-types.mjs          write / update / delete stale files
 *   node scripts/css-module-types.mjs --check  fail if anything is out of date (CI, pre-commit)
 *   node scripts/css-module-types.mjs a.module.scss b.module.scss   only these files
 */
import { existsSync, globSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import postcss from 'postcss'
import selectorParser from 'postcss-selector-parser'
import * as sass from 'sass'

const ROOT = process.cwd()
const SRC = path.join(ROOT, 'src')
const HEADER = '// Generated by scripts/css-module-types.mjs. Do not edit manually.\n'
const VALID_IDENTIFIER = /^[A-Za-z_$][\w$]*$/

const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const explicitFiles = args.filter((arg) => arg.endsWith('.module.scss'))

/** @param {string} css */
function collectClassNames(css) {
  /** @type {Set<string>} */
  const classNames = new Set()
  const parser = selectorParser((selectors) => {
    selectors.walkClasses((node) => {
      let parent = node.parent
      while (parent) {
        if (parent.type === 'pseudo' && parent.value === ':global') return
        parent = parent.parent
      }
      classNames.add(node.value)
    })
  })

  postcss.parse(css).walkRules((rule) => {
    if (
      rule.parent?.type === 'atrule' &&
      /keyframes$/i.test(/** @type {postcss.AtRule} */ (rule.parent).name)
    ) {
      return
    }
    parser.processSync(rule.selector)
  })

  return [...classNames].toSorted((a, b) => a.localeCompare(b))
}

/** @param {string} file */
function renderDeclaration(file) {
  const { css } = sass.compile(file, { loadPaths: [SRC], style: 'expanded' })
  const classNames = collectClassNames(css)
  const invalid = classNames.filter((name) => !VALID_IDENTIFIER.test(name))
  if (invalid.length > 0) {
    throw new Error(
      `${path.relative(ROOT, file)}: class names must be camelCase, got: ${invalid.join(', ')}`
    )
  }

  const fields = classNames.map((name) => `  readonly ${name}: string\n`).join('')
  return `${HEADER}declare const styles: {\n${fields}}\n\nexport default styles\n`
}

const sources = (explicitFiles.length > 0 ? explicitFiles : globSync('src/**/*.module.scss')).map(
  (file) => path.resolve(ROOT, file)
)

/** @type {string[]} */
const problems = []

for (const source of sources) {
  const target = `${source}.d.ts`
  const expected = renderDeclaration(source)
  const actual = existsSync(target) ? readFileSync(target, 'utf8') : null
  if (actual === expected) continue

  if (checkOnly)
    problems.push(`${actual === null ? 'missing' : 'outdated'}: ${path.relative(ROOT, target)}`)
  else writeFileSync(target, expected)
}

if (explicitFiles.length === 0) {
  for (const declaration of globSync('src/**/*.module.scss.d.ts')) {
    if (existsSync(declaration.slice(0, -'.d.ts'.length))) continue
    if (checkOnly) problems.push(`orphaned: ${declaration}`)
    else rmSync(declaration)
  }
}

if (problems.length > 0) {
  console.error(
    `CSS module types are out of date. Run \`npm run css:types\`.\n  ${problems.join('\n  ')}`
  )
  process.exit(1)
}
